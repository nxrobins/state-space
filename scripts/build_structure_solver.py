"""Build the portable exact planner with Clang; runtime never invokes a compiler."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent


def source_inputs(root=ROOT):
    catalog = json.loads((root / "engine/materials.json").read_text())
    constants = {"COLD_STRIDE": catalog["cold_stride"]}
    constants.update({"COLD_" + name.upper(): i for i, name in enumerate(catalog["cold_fields"])})
    constants.update({"PHASE_" + name.upper(): value for name, value in catalog["phases"].items()})
    constants.update({"INTEGRITY": 255, "ANCHOR": 4096, "BOND_LEFT": 256, "BOND_RIGHT": 512, "BOND_UP": 1024, "BOND_DOWN": 2048})
    header = "\n".join(f"#define {name} {value}u" for name, value in constants.items()) + "\n"
    source = (root / "engine/structure_solver.c").read_text(encoding="utf-8").encode("utf-8")
    return source, header


def check_compiled(root=ROOT):
    source, header = source_inputs(root)
    out = root / "engine/generated"
    wasm = (out / "structure_solver.wasm").read_bytes()
    receipt = json.loads((out / "structure_solver.json").read_text())
    expected = "// Generated by scripts/build_structure_solver.py.\nexport const STRUCTURE_WASM = '" + base64.b64encode(wasm).decode() + "';\n"
    return (receipt["abiVersion"] == 1 and receipt["sourceHash"] == hashlib.sha256(source + header.encode()).hexdigest()
            and receipt["wasmHash"] == hashlib.sha256(wasm).hexdigest()
            and (out / "structure_solver.ts").read_text() == expected)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clang", default=shutil.which("clang"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, header = source_inputs()
    input_hash = hashlib.sha256(source + header.encode()).hexdigest()
    out = ROOT / "engine/generated"
    wasm = out / "structure_solver.wasm"
    manifest = out / "structure_solver.json"
    if args.check:
        if not check_compiled():
            raise ValueError("Compiled structural solver drift; rebuild it with Clang")
        return
    if not args.clang:
        raise RuntimeError("Clang is required only to rebuild the structural solver")
    with tempfile.TemporaryDirectory() as folder:
        path = Path(folder)
        (path / "structure_constants.h").write_text(header)
        (path / "solver.c").write_bytes(source)
        command = [args.clang, "--target=wasm32", "-O3", "-ffreestanding", "-fno-builtin", "-nostdlib", "-mbulk-memory",
                   "-Wl,--no-entry", "-Wl,--export=solve", "-Wl,--export=weight", "-Wl,--export=abi_version", "-Wl,--export=__heap_base",
                   "-Wl,--export=validate", "-Wl,--export=ledger", "-Wl,--export=ledger_total", "-Wl,--export=ledger_sensible", "-Wl,--export=ledger_chemical",
                   "-Wl,--export-memory", "-Wl,--initial-memory=131072", "-o", str(path / "solver.wasm"), str(path / "solver.c")]
        subprocess.run(command, check=True, timeout=60)
        wasm.write_bytes((path / "solver.wasm").read_bytes())
    (out / "structure_solver.ts").write_text("// Generated by scripts/build_structure_solver.py.\nexport const STRUCTURE_WASM = '" + base64.b64encode(wasm.read_bytes()).decode() + "';\n", encoding="utf-8")
    manifest.write_text(json.dumps({"abiVersion": 1, "sourceHash": input_hash, "wasmHash": hashlib.sha256(wasm.read_bytes()).hexdigest(),
                                   "compiler": subprocess.check_output([args.clang, "--version"], text=True).splitlines()[0]}, indent=2, allow_nan=False) + "\n")
    print(f"Compiled exact structural solver: {wasm.stat().st_size} bytes")


if __name__ == "__main__":
    main()
